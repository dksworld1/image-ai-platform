package com.imageaiplatform.foundation;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.options;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.imageaiplatform.foundation.config.MyBatisConfigurationProperties;
import com.imageaiplatform.foundation.dao.FoundationProbeDao;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.apache.ibatis.session.SqlSessionFactory;
import javax.sql.DataSource;
import org.springframework.jdbc.core.JdbcTemplate;
import jakarta.servlet.Filter;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;

@SpringBootTest(properties = {
        "app.auth.jwt.secret=local-profile-test-only-signing-key-32-bytes",
        "datasource.app.url=jdbc:h2:mem:local-app;DB_CLOSE_DELAY=-1",
        "datasource.catalog.url=jdbc:h2:mem:local-catalog;DB_CLOSE_DELAY=-1",
        "datasource.archive.url=jdbc:h2:mem:local-archive;DB_CLOSE_DELAY=-1"
})
@ActiveProfiles("local")
class LocalProfileConfigurationTest {
    @Autowired
    private WebApplicationContext webContext;

    @Autowired
    @Qualifier("springSecurityFilterChain")
    private Filter securityFilter;

    @Test
    void allowsLocalFrontendPreflightWithoutAuthentication() throws Exception {
        var mvc = MockMvcBuilders.webAppContextSetup(webContext).addFilters(securityFilter).build();
        for (String origin : new String[] {"http://localhost:5173", "http://localhost:4173",
                "http://127.0.0.1:5173", "http://127.0.0.1:4173"}) {
            mvc.perform(options("/api/auth/token")
                            .header("Origin", origin)
                            .header("Access-Control-Request-Method", "POST")
                            .header("Access-Control-Request-Headers", "authorization,content-type"))
                    .andExpect(status().is2xxSuccessful())
                    .andExpect(header().string("Access-Control-Allow-Origin", origin));
        }
    }

    @Test
    void allowsBrowserLoginFromLocalhostAndLoopbackOrigins() throws Exception {
        var mvc = MockMvcBuilders.webAppContextSetup(webContext).addFilters(securityFilter).build();
        for (String origin : new String[] {"http://localhost:5173", "http://localhost:4173",
                "http://127.0.0.1:5173", "http://127.0.0.1:4173"}) {
            mvc.perform(post("/api/auth/token").header("Origin", origin).contentType("application/json")
                            .content("{\"username\":\"admin\",\"password\":\"admin\"}"))
                    .andExpect(status().isOk())
                    .andExpect(header().string("Access-Control-Allow-Origin", origin))
                    .andExpect(jsonPath("$.accessToken").isNotEmpty());
        }
    }

    @Test
    void rejectsPreflightFromUnlistedOrigin() throws Exception {
        var mvc = MockMvcBuilders.webAppContextSetup(webContext).addFilters(securityFilter).build();
        mvc.perform(options("/api/auth/token")
                        .header("Origin", "https://unlisted.example")
                        .header("Access-Control-Request-Method", "POST"))
                .andExpect(status().isForbidden())
                .andExpect(header().doesNotExist("Access-Control-Allow-Origin"));
    }

    @Autowired
    private MyBatisConfigurationProperties myBatisProperties;

    @Autowired
    @Qualifier("catalogSqlSessionFactory")
    private SqlSessionFactory catalogSqlSessionFactory;

    @Autowired
    @Qualifier("catalogFoundationProbeDao")
    private FoundationProbeDao catalogDao;

    @Autowired
    @Qualifier("catalogDataSource")
    private DataSource catalogDataSource;

    @Test
    void importsLocalDatasourceAndLogConfiguration() {
        assertThat(myBatisProperties.getConfigLocation()).isEqualTo("classpath:config/mybatis-config.xml");
        assertThat(myBatisProperties.getMapperLocations()).isEqualTo("classpath*:mapper/**/*.xml");
        assertThat(catalogSqlSessionFactory.getConfiguration().isMapUnderscoreToCamelCase()).isTrue();

        new JdbcTemplate(catalogDataSource).execute("""
                CREATE TABLE IF NOT EXISTS foundation_probe (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    probe_value VARCHAR(100) NOT NULL
                )
                """);

        String value = "local-profile-smoke";
        assertThat(catalogDao.countByValue(value)).isZero();
        assertThat(catalogDao.insert(value)).isEqualTo(1);
    }
}
